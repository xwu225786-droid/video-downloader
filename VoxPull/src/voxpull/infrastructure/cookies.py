from __future__ import annotations

import os
import json
import tempfile
import time
from pathlib import Path
from typing import Any


def has_douyin_login_cookie(cookies: list[dict[str, Any]]) -> bool:
    return any(
        (str(cookie.get("domain", "")).lstrip(".") == "douyin.com"
         or str(cookie.get("domain", "")).endswith(".douyin.com"))
        and cookie.get("name") in {"sessionid", "sessionid_ss"}
        and bool(cookie.get("value"))
        and (cookie.get("expires", -1) <= 0 or cookie["expires"] > time.time())
        for cookie in cookies
    )


def save_storage_state(path: Path, state: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    name = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent,
                                         prefix=".auth-", delete=False) as output:
            name = output.name
            json.dump(state, output, ensure_ascii=False)
        os.replace(name, path)
        path.chmod(0o600)
    finally:
        if name is not None:
            Path(name).unlink(missing_ok=True)


def write_netscape_cookie_file(cookies: list[dict[str, Any]], destination: Path) -> None:
    """Write Playwright cookies in the format accepted by yt-dlp."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Netscape HTTP Cookie File", "# Generated by VoxPull; do not share.", ""]
    for cookie in cookies:
        name = str(cookie.get("name", ""))
        value = str(cookie.get("value", ""))
        domain = str(cookie.get("domain", ""))
        if not name or not domain or any(ch in name + value for ch in "\r\n\t"):
            continue
        include_subdomains = "TRUE" if domain.startswith(".") else "FALSE"
        if cookie.get("httpOnly"):
            domain = f"#HttpOnly_{domain}"
        path = str(cookie.get("path") or "/")
        secure = "TRUE" if cookie.get("secure") else "FALSE"
        expires_raw = cookie.get("expires", 0)
        expires = (
            int(expires_raw) if isinstance(expires_raw, (int, float)) and expires_raw > 0 else 0
        )
        lines.append(
            "\t".join((domain, include_subdomains, path, secure, str(expires), name, value))
        )
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(destination, 0o600)
